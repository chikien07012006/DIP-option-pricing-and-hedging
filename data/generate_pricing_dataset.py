from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import qmc

from pricing.analytical import reiner_rubinstein_dip


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT_PATH = PROJECT_ROOT / "data" / "pricing_dataset.csv"


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a synthetic down-and-in put pricing dataset."
    )
    parser.add_argument(
        "--num-samples",
        type=int,
        default=140_000,
        help="Number of valid contracts to generate (default: 140000).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed used by Latin Hypercube Sampling (default: 42).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help="Output CSV path (default: data/pricing_dataset.csv).",
    )
    return parser.parse_args()


def scale_to_range(values: np.ndarray, lower: float, upper: float) -> np.ndarray:
    """Scale values from [0, 1] to [lower, upper]."""
    return lower + values * (upper - lower)


def sample_valid_contracts(num_samples: int, seed: int) -> pd.DataFrame:
    """Sample valid DIP contracts with Latin Hypercube Sampling.

    The sampled fields follow the ranges in the project proposal. Samples that
    violate ``barrier_level < strike_price`` are discarded and replenished.
    """
    if num_samples <= 0:
        raise ValueError("num_samples must be positive.")

    rng = np.random.default_rng(seed)
    batches: list[pd.DataFrame] = []
    accepted_rows = 0

    while accepted_rows < num_samples:
        remaining = num_samples - accepted_rows
        # Oversampling limits repeated LHS calls after invalid contracts are removed.
        batch_size = max(int(np.ceil(remaining * 1.25)), 1_024)
        sampler = qmc.LatinHypercube(d=6, seed=int(rng.integers(0, 2**32 - 1)))
        unit_samples = sampler.random(n=batch_size)

        spot_price = scale_to_range(unit_samples[:, 0], 80.0, 120.0)
        strike_price = scale_to_range(unit_samples[:, 1], 80.0, 120.0)
        barrier_to_spot_ratio = scale_to_range(unit_samples[:, 2], 0.65, 0.95)
        time_to_maturity = scale_to_range(unit_samples[:, 3], 0.1, 2.0)
        volatility = scale_to_range(unit_samples[:, 4], 0.10, 0.50)
        risk_free_rate = scale_to_range(unit_samples[:, 5], 0.00, 0.10)
        barrier_level = spot_price * barrier_to_spot_ratio

        valid = barrier_level < strike_price
        batch = pd.DataFrame(
            {
                "spot_price": spot_price[valid],
                "strike_price": strike_price[valid],
                "barrier_level": barrier_level[valid],
                "barrier_to_spot_ratio": barrier_to_spot_ratio[valid],
                "time_to_maturity": time_to_maturity[valid],
                "volatility": volatility[valid],
                "risk_free_rate": risk_free_rate[valid],
            }
        )
        batches.append(batch)
        accepted_rows += len(batch)

    contracts = pd.concat(batches, ignore_index=True).iloc[:num_samples].copy()
    return contracts


def add_analytical_labels(contracts: pd.DataFrame) -> pd.DataFrame:
    """Add continuous-monitoring DIP prices generated by the analytical engine."""
    prices = [
        reiner_rubinstein_dip(
            S=row.spot_price,
            K=row.strike_price,
            H=row.barrier_level,
            T=row.time_to_maturity,
            r=row.risk_free_rate,
            sigma=row.volatility,
        )
        for row in contracts.itertuples(index=False)
    ]

    labeled_contracts = contracts.copy()
    labeled_contracts["analytical_price"] = prices
    return labeled_contracts


def main() -> None:
    args = parse_arguments()
    contracts = sample_valid_contracts(args.num_samples, args.seed)
    dataset = add_analytical_labels(contracts)

    output_path = args.output.expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    dataset.to_csv(output_path, index=False, float_format="%.10f")

    print(f"Saved {len(dataset):,} contracts to: {output_path}")
    print("Label engine: continuous Reiner--Rubinstein down-and-in put pricing")


if __name__ == "__main__":
    main()
